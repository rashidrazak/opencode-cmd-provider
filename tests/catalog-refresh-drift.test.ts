interface Repo {
  work: string
  cleanup: () => Promise<void>
}

async function setupRepo(): Promise<Repo> {
  const base = await mkdtemp(join(tmpdir(), "cc-cron-drift-"))
  const remote = join(base, "remote.git")
  const work = join(base, "work")
  await exec("git", ["init", "--bare", "-q", remote])
  await exec("git", ["init", "-q", "-b", "main", work])
  await exec("git", ["-C", work, "config", "user.email", "test@example.com"])
  await exec("git", ["-C", work, "config", "user.name", "Test"])
  await exec("git", ["-C", work, "config", "commit.gpgsign", "false"])
  await exec("git", ["-C", work, "remote", "add", "origin", remote])
  for (const [path, lines] of Object.entries(GENERATED_FILES)) {
    await mkdir(join(work, path, ".."), { recursive: true })
    await writeFile(join(work, path), lines.join("\n"), "utf-8")
  }
  await exec("git", ["-C", work, "add", "-A"])
  await exec("git", ["-C", work, "commit", "-q", "-m", "seed generated catalogs"])
  await exec("git", ["-C", work, "push", "-q", "origin", "main"])
  return {
    work,
    cleanup: async () => await rm(base, { recursive: true, force: true }),
  }
}

async function runFragment(fragment: string, work: string): Promise<{ code: number; out: string }> {
  try {
    const { stdout } = await exec("bash", ["-c", fragment], { cwd: work })
    return { code: 0, out: stdout }
  } catch (error) {
    const err = error as { code?: number; stdout?: string }
    return { code: err.code ?? 1, out: err.stdout ?? "" }
  }
}

/** Applies a mutation to the working tree (the "after" cron state). */
async function mutate(work: string, path: string, lines: string[]): Promise<void> {
  await mkdir(join(work, path, ".."), { recursive: true })
  await writeFile(join(work, path), lines.join("\n"), "utf-8")
}

/** Returns the file lines with every line matching `match` replaced. */
function withLineReplaced(lines: string[], match: string | RegExp, replacement: string): string[] {
  return lines.map((line) =>
    typeof match === "string"
      ? line === match
        ? replacement
        : line
      : match.test(line)
        ? replacement
        : line,
  )
}

run([
  [
    "drift: a date-only-churn run with churned fixtures opens no PR (the #103 replay ships nothing)",
    async () => {
      const repo = await setupRepo()
      try {
        // The nothing-changed run: every generated module identical
        // except the refreshed-date stamps, fixture bytes churned
        // (upstream site deploy → new build ids).
        await mutate(
          repo.work,
          "src/catalog/facts.ts",
          withLineReplaced(
            GENERATED_FILES["src/catalog/facts.ts"],
            /^export const FACTS_LAST_REFRESHED/,
            'export const FACTS_LAST_REFRESHED = "2026-09-02"',
          ),
        )
        await mutate(
          repo.work,
          "src/catalog/classification.ts",
          withLineReplaced(
            GENERATED_FILES["src/catalog/classification.ts"],
            /^export const CLASSIFICATION_LAST_REFRESHED/,
            'export const CLASSIFICATION_LAST_REFRESHED = "2026-09-02"',
          ),
        )
        await mutate(
          repo.work,
          "src/deals/catalog.ts",
          withLineReplaced(
            GENERATED_FILES["src/deals/catalog.ts"],
            /^export const DEAL_LAST_REFRESHED/,
            'export const DEAL_LAST_REFRESHED = "2026-09-02"',
          ),
        )
        await mutate(repo.work, "tests/fixtures/rsc-goat.txt", [
          '2:[{"slug":"kimi-k3","id":"moonshotai/Kimi-K3","build":"bbb-churned"}]',
          "",
        ])
        const post = await runFragment(DRIFT_FRAGMENT, repo.work)
        assertEqual(post.code, 0)
        assert(
          post.out.includes("drift=false"),
          `date-only churn must not count as drift, got: ${post.out}`,
        )
        // Sensitivity check: the pre-fix raw byte-diff WOULD have opened
        // the no-op PR #103 produced. If this ever stops holding, the
        // ignores have stopped doing their job.
        const pre = await runFragment(PREFIX_FRAGMENT, repo.work)
        assert(
          pre.out.includes("drift=true"),
          "the pre-fix fragment must report drift on date-only churn (documents the bug)",
        )
      } finally {
        await repo.cleanup()
      }
    },
  ],
  [
    "drift: a real data change in any generated module still opens the refresh PR",
    async () => {
      const repo = await setupRepo()
      try {
        // A capability value moves (the same date stamps otherwise).
        await mutate(
          repo.work,
          "src/catalog/classification.ts",
          withLineReplaced(
            withLineReplaced(
              GENERATED_FILES["src/catalog/classification.ts"],
              /^export const CLASSIFICATION_LAST_REFRESHED/,
              'export const CLASSIFICATION_LAST_REFRESHED = "2026-09-02"',
            ),
            '  "moonshotai/Kimi-K3": true,',
            '  "moonshotai/Kimi-K3": false,',
          ),
        )
        const post = await runFragment(DRIFT_FRAGMENT, repo.work)
        // The step signals drift through $GITHUB_OUTPUT, not its exit
        // code (the if/else's last command is `git diff --stat`, which
        // exits 0 on both branches).
        assert(
          post.out.includes("drift=true"),
          `a real classification change must count as drift, got: ${post.out}`,
        )
      } finally {
        await repo.cleanup()
      }
    },
  ],
  [
    "drift: a facts source/package-version line move still counts as drift",
    async () => {
      const repo = await setupRepo()
      try {
        // A real upstream package event: the facts source URL and
        // package version move to a new command-code release.
        await mutate(
          repo.work,
          "src/catalog/facts.ts",
          withLineReplaced(
            withLineReplaced(
              GENERATED_FILES["src/catalog/facts.ts"],
              /^export const FACTS_SOURCE_URL/,
              'export const FACTS_SOURCE_URL = "https://unpkg.com/command-code@1.40.0/dist/bundled/command-code-knowledge/reference/models.md"',
            ),
            /^export const FACTS_PACKAGE_VERSION/,
            'export const FACTS_PACKAGE_VERSION = "1.40.0"',
          ),
        )
        const post = await runFragment(DRIFT_FRAGMENT, repo.work)
        assert(
          post.out.includes("drift=true"),
          `a facts package-version move must count as drift, got: ${post.out}`,
        )
      } finally {
        await repo.cleanup()
      }
    },
  ],
  [
    "drift: fixture-only changes never open a PR",
    async () => {
      const repo = await setupRepo()
      try {
        // Only the fixture bytes churn; the generated modules are
        // byte-identical to main.
        await mutate(repo.work, "tests/fixtures/rsc-pro.txt", [
          '2:[{"slug":"kimi-k3","id":"moonshotai/Kimi-K3","build":"ccc-deploy"}]',
          "",
        ])
        const post = await runFragment(DRIFT_FRAGMENT, repo.work)
        assertEqual(post.code, 0)
        assert(
          post.out.includes("drift=false"),
          `fixture-only churn must not open a PR, got: ${post.out}`,
        )
      } finally {
        await repo.cleanup()
      }
    },
  ],
])
