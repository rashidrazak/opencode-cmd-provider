// tests/catalog-refresh-drift.test.ts — seam: the `Detect drift against
// main` step in `.github/workflows/catalog-refresh.yml` (issue #113).
//
// The cron's drift check used to be a raw byte-diff over the generated
// modules AND the RSC fixtures. That opened no-op PRs: a run where
// nothing upstream changed still produced a PR whose only diff was the
// refreshed-date stamps (PR #103 is exactly this), and fixture bytes
// churn with upstream site deploys (build-id hashes) even when the data
// is identical. The fix judges **meaningful** drift: only the generated
// catalog modules, with the release gate's established date-stamp
// ignores (the refreshed-date lines of the facts, deals, and
// classification modules) — the same convention ADR-0003's release gate
// uses, so the cron and the release gate agree on what counts as "no
// change". Movements of the facts source/package-version lines remain
// meaningful (they signal a real upstream package event). Fixtures keep
// riding along in meaningful refresh commits but no longer decide drift.
//
// Per the repo's cron-workflow test pattern, this test spawns the exact
// shell fragment the workflow runs, against synthetic before/after git
// trees. It also documents the original failure mode: the pre-fix
// fragment (no date-stamp ignores) reports drift on date-only churn —
// the sensitivity check that keeps the ignores from being dropped.
import { execFile } from "node:child_process"
import { mkdtemp, rm, writeFile, mkdir } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { promisify } from "node:util"
import { assert, assertEqual, run } from "./harness.js"

const exec = promisify(execFile)

// The exact drift-check fragment the workflow runs (see the
// `Detect meaningful drift against main` step in
// `.github/workflows/catalog-refresh.yml`). If the workflow's fragment
// changes, update this copy in the same commit — a divergence here means
// the workflow is no longer locked by the test.
const DRIFT_FRAGMENT = `
  git fetch origin main
  if git diff --quiet \
      -I 'FACTS_LAST_REFRESHED' \
      -I 'DEAL_LAST_REFRESHED' \
      -I 'CLASSIFICATION_LAST_REFRESHED' \
      origin/main -- \\
      src/catalog/snapshot.ts \\
      src/catalog/facts.ts \\
      src/catalog/classification.ts \\
      src/deals/catalog.ts; then
    echo "drift=false"
  else
    echo "drift=true"
    git diff --stat \\
      -I 'FACTS_LAST_REFRESHED' \\
      -I 'DEAL_LAST_REFRESHED' \\
      -I 'CLASSIFICATION_LAST_REFRESHED' \\
      origin/main -- \\
      src/catalog/snapshot.ts \\
      src/catalog/facts.ts \\
      src/catalog/classification.ts \\
      src/deals/catalog.ts
  fi
`

// The pre-fix fragment: a raw byte-diff including the fixture files —
// exactly what opened no-op PR #103. Kept as the negative control.
const PREFIX_FRAGMENT = `
  git fetch origin main
  if git diff --quiet origin/main -- \\
      src/catalog/snapshot.ts \\
      src/catalog/facts.ts \\
      src/catalog/classification.ts \\
      src/deals/catalog.ts \\
      tests/fixtures/rsc-pricing-limits.txt \\
      tests/fixtures/rsc-goat.txt \\
      tests/fixtures/rsc-pro.txt; then
    echo "drift=false"
  else
    echo "drift=true"
  fi
`

