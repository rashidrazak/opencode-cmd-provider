// tests/auto-release.test.ts — seam: the auto-release flow (issue #115).
// Merging a catalog-refresh PR cuts a patch release: version bump, lockfile
// sync, a CHANGELOG section authored from the merged PR body's semantic
// sections, a bot-authored `chore(release): X.Y.Z` commit on main, and a
// `vX.Y.Z` tag — which triggers the unchanged tag-driven release pipeline
// (one publish path, ADR-0002).
//
// Per the repo's cron-workflow test pattern, the bump/commit/tag shell
// fragment is spawned against a synthetic repository (local bare remote
// standing in for origin), and the CHANGELOG authoring is exercised as a
// pure module over a synthetic PR body. The merged PR body is untrusted
// upstream-derived input: it travels env → file → module (read as data),
// never interpolated into run scripts.
import { execFile } from "node:child_process"
import { cp, mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { promisify } from "node:util"
import { buildChangelogSection } from "../scripts/release-notes.mjs"
import { assert, assertEqual, run } from "./harness.js"

const exec = promisify(execFile)

const TODAY = new Date().toISOString().split("T")[0]

