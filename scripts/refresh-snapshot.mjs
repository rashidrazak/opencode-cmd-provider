// scripts/refresh-snapshot.mjs — regenerate src/catalog/snapshot.ts and
// src/catalog/facts.ts from the live Command Code model catalog. Runs at
// release time; never at runtime.
//
// Usage: node scripts/refresh-snapshot.mjs [--out path] [--facts-out path]
//   --out        write the snapshot to this path (default src/catalog/snapshot.ts)
//   --facts-out  write the facts to this path (default <out dir>/facts.ts)
//   env COMMANDCODE_API_BASE overrides the API base (tests point at the mock)
//   env COMMANDCODE_REGISTRY_URL overrides the npm registry URL (tests point at the mock)
//   env COMMANDCODE_FACTS_URL overrides the models.md URL (tests point at the mock)
import { mkdir, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"

const DEFAULT_API_BASE = "https://api.commandcode.ai"
const DEFAULT_OUT = resolve(import.meta.dirname, "..", "src", "catalog", "snapshot.ts")
const DEFAULT_REGISTRY_URL = "https://registry.npmjs.org/command-code"
const DEFAULT_FACTS_URL = (version) =>
  `https://unpkg.com/command-code@${version}/dist/bundled/command-code-knowledge/reference/models.md`

const registryUrl = process.env.COMMANDCODE_REGISTRY_URL ?? DEFAULT_REGISTRY_URL

function argValue(name) {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : undefined
}

function isRecord(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value)
}

function fail(message) {
  console.error(`refresh-snapshot: ${message}`)
  process.exit(1)
}

async function fetchOrFail(url, headers) {
  let response
  try {
    response = await fetch(url, headers)
  } catch (error) {
    fail(`could not fetch ${url}: ${error instanceof Error ? error.message : String(error)}`)
  }
  if (!response.ok) {
    fail(`failed to fetch ${url}: ${response.status} ${response.statusText}`)
  }
  return response
}

async function fetchJson(url) {
  const response = await fetchOrFail(url, { headers: { accept: "application/json" } })
  try {
    return await response.json()
  } catch (error) {
    fail(`could not parse ${url}: ${error instanceof Error ? error.message : String(error)}`)
  }
}

function parseCatalog(body) {
  if (!isRecord(body)) fail("expected models response to be an object")
  if (body.object !== "list")
    fail(`expected models response object to be 'list', got ${body.object}`)
  if (!Array.isArray(body.data)) fail("expected models response data to be an array")
  return body.data.map((entry) => {
    if (!isRecord(entry)) fail("expected model entry to be an object")
    const id = entry.id
    if (typeof id !== "string" || id.length === 0)
      fail("expected model id to be a non-empty string")
    const name = entry.name
    if (typeof name !== "string" || name.length === 0) {
      fail(`expected model ${id} name to be a non-empty string`)
    }
    const contextLength = entry.context_length
    if (
      typeof contextLength !== "number" ||
      !Number.isFinite(contextLength) ||
      contextLength <= 0
    ) {
      fail(`expected model ${id} context_length to be a positive number`)
    }
    return { id, name, contextLength }
  })
}

function renderSnapshot(models) {
  const lines = models.map(
    (model) =>
      `  { id: ${JSON.stringify(model.id)}, name: ${JSON.stringify(model.name)}, contextLength: ${model.contextLength} },`,
  )
  return [
    "// src/catalog/snapshot.ts — GENERATED by scripts/refresh-snapshot.mjs. Do not edit.",
    "//",
    "// A copy of the Command Code model catalog (id, name, context length) bundled",
    "// in the package so the plugin can auto-register every model without network",
    "// access at runtime. Regenerate with `npm run refresh:snapshot`.",
    "",
    "export interface CatalogModel {",
    "  readonly id: string",
    "  readonly name: string",
    "  readonly contextLength: number",
    "}",
    "",
    `export const MODEL_SNAPSHOT: readonly CatalogModel[] = [`,
    ...lines,
    "]",
    "",
  ].join("\n")
}

function renderFacts({ sourceUrl, packageVersion, lastRefreshed, efforts, costs }) {
  const effortLines = Object.entries(efforts).map(
    ([id, levels]) => `  ${JSON.stringify(id)}: ${JSON.stringify(levels)},`,
  )
  const costLines = Object.entries(costs).map(
    ([id, cost]) =>
      `  ${JSON.stringify(id)}: { input: ${cost.input}, output: ${cost.output}, cacheRead: ${cost.cacheRead}, cacheWrite: ${cost.cacheWrite} },`,
  )
  return [
    "// src/catalog/facts.ts — GENERATED by scripts/refresh-snapshot.mjs. Do not edit.",
    "//",
    "// Capability facts (reasoning efforts + per-1M-token rates) parsed from the",
    "// command-code npm package's bundled model catalog (models.md). Regenerate",
    "// with `npm run refresh:snapshot`.",
    "",
    `export const FACTS_SOURCE_URL = ${JSON.stringify(sourceUrl)}`,
    `export const FACTS_PACKAGE_VERSION = ${JSON.stringify(packageVersion)}`,
    `export const FACTS_LAST_REFRESHED = ${JSON.stringify(lastRefreshed)}`,
    "",
    "export const MODEL_EFFORTS: Readonly<Record<string, readonly string[]>> = {",
    ...effortLines,
    "}",
    "",
    "export const MODEL_COSTS: Readonly<",
    "  Record<string, { input: number; output: number; cacheRead: number; cacheWrite: number }>",
    "> = {",
    ...costLines,
    "}",
    "",
  ].join("\n")
}

const base = process.env.COMMANDCODE_API_BASE ?? DEFAULT_API_BASE
const catalog = await fetchJson(`${base}/provider/v1/models`)
const models = parseCatalog(catalog)
if (models.length === 0) fail("Command Code returned an empty model catalog")

const out = argValue("--out") ?? DEFAULT_OUT
const factsOut = argValue("--facts-out") ?? resolve(dirname(out), "facts.ts")

// --- Capability facts (reasoning efforts + rates) from the CLI catalog ---
// Both parses complete before either file is written so a failure never
// leaves a partial refresh (a fresh snapshot.ts next to stale/missing facts).
const { parseFactsMarkdown } = await import("./parse-facts.mjs")
const registry = await fetchJson(registryUrl)
const latest = registry?.["dist-tags"]?.latest
if (typeof latest !== "string" || latest.length === 0) {
  fail(`could not resolve latest command-code version from ${registryUrl}`)
}
const factsUrl = process.env.COMMANDCODE_FACTS_URL ?? DEFAULT_FACTS_URL(latest)
const factsMarkdown = await (
  await fetchOrFail(factsUrl, { headers: { accept: "text/markdown" } })
).text()
const { efforts, costs } = parseFactsMarkdown(factsMarkdown)

await mkdir(dirname(out), { recursive: true })
await writeFile(out, renderSnapshot(models), "utf-8")
console.log(`refresh-snapshot: wrote ${models.length} models to ${out}`)
await writeFile(
  factsOut,
  renderFacts({
    sourceUrl: factsUrl,
    packageVersion: latest,
    lastRefreshed: new Date().toISOString().split("T")[0],
    efforts,
    costs,
  }),
  "utf-8",
)
console.log(
  `refresh-snapshot: wrote facts (${Object.keys(efforts).length} efforts, ${Object.keys(costs).length} costs) for command-code@${latest} to ${factsOut}`,
)
